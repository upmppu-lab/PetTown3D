        string line = pool[Random.Range(0, pool.Length)];
        return line.Replace("{pet}", string.IsNullOrEmpty(petName) ? "펫" : petName);
    }

    public static int Count
    {
        get { int n = 0; foreach (var p in lines.Values) n += p.Length; return n; }
    }
